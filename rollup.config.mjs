import typescript from "@rollup/plugin-typescript";
import { transformSync } from "esbuild";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

function readBuiltJs(name) {
    return readFileSync(join(pkgRoot, "dist", name), "utf8").replaceAll(
        "</script",
        "<\\/script"
    );
}

function writeGenerated(file, name, value) {
    // Committed because the publishing service builds src/index.ts with
    // esbuild and runs no bundler plugins.
    const out = join(pkgRoot, "src", file);
    const source =
        `// Generated by rollup.config.mjs. Do not edit by hand.\n` +
        `export const ${name} = ${JSON.stringify(value)};\n`;
    // Skipping identical writes keeps the dev server's rebuild-on-change from looping.
    if (!existsSync(out) || readFileSync(out, "utf8") !== source)
        writeFileSync(out, source);
}

